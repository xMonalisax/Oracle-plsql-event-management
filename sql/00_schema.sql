CREATE TABLE Utilizatori (
    Id_utilizator NUMBER(10) PRIMARY KEY,
    Nume VARCHAR2(50) NOT NULL,
    Email VARCHAR2(100) NOT NULL UNIQUE
);

CREATE TABLE Evenimente (
    Id_eveniment NUMBER(10) PRIMARY KEY,
    Nume_eveniment VARCHAR2(100) NOT NULL,
    Data_eveniment DATE NOT NULL,
    Descriere VARCHAR2(255),
    Id_utilizator NUMBER(10) NOT NULL,
    CONSTRAINT fk_evenimente_utilizatori FOREIGN KEY (Id_utilizator)
        REFERENCES Utilizatori(Id_utilizator)
);

CREATE TABLE Tipuri_evenimente (
    Id_tip_eveniment NUMBER(10) PRIMARY KEY,
    Tip_eveniment VARCHAR2(50) NOT NULL
);

CREATE TABLE Legatura_evenimente_tip (
    Id_eveniment NUMBER(10) NOT NULL,
    Id_tip_eveniment NUMBER(10) NOT NULL,
    CONSTRAINT pk_legatura_evenimente_tip PRIMARY KEY (Id_eveniment, Id_tip_eveniment),
    CONSTRAINT fk_legatura_eveniment FOREIGN KEY (Id_eveniment)
        REFERENCES Evenimente(Id_eveniment),
    CONSTRAINT fk_legatura_tip FOREIGN KEY (Id_tip_eveniment)
        REFERENCES Tipuri_evenimente(Id_tip_eveniment)
);

CREATE TABLE Istoric_Descrieri_Evenimente (
    Id_istoric NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    Id_eveniment NUMBER(10) NOT NULL,
    Descriere_veche VARCHAR2(255),
    Data_modificare TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
